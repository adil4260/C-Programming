#include <stdio.h>

int main()
{
    int N;
    scanf("%d", &N); // N এর মান ইনপুট নেওয়া[cite: 8]

    int even = 2; // জোড় সংখ্যা প্রিন্ট করার জন্য ভ্যারিয়েবল[cite: 8]

    for (int i = 0; i < N; i++)
    {
        for (int j = 0; j < N; j++)
        {
            // গ্রিডের পজিশন চেক করা (জোড় ইনডেক্সে 0 এবং বিজোড় ইনডেক্সে জোড় সংখ্যা প্রিন্ট হবে)
            if ((i * N + j) % 2 == 0)
            {
                printf("%d\t", 0);
            }
            else
            {
                printf("%d\t", even);
                even += 2; // জোড় সংখ্যা ২ করে বৃদ্ধি পাবে[cite: 8]
            }
        }
        printf("\n"); // প্রতি সারির শেষে নতুন লাইনে যাওয়ার জন্য[cite: 8]
    }

    return 0;
}